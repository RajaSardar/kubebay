import type { BestPracticeCheck, BestPracticesInput } from "./bestPractices";
import { matchesSelector, type LabelSelector } from "./labelSelector";

type Obj = Record<string, unknown>;
const rec = (v: unknown): Obj => (v && typeof v === "object" && !Array.isArray(v) ? (v as Obj) : {});
const str = (v: unknown): string => (typeof v === "string" ? v : "");

/**
 * Generated YAML for a failing check, opened in a "New resource" dock tab for the
 * user to read, dry-run and apply. Kubebay never applies it by itself.
 */
export interface BpFix {
  /** The kind the editor opens on (the first document's). */
  kind: string;
  /** Documents generated. */
  count: number;
  yaml: string;
}

// A tiny YAML writer for the generated objects: every string is double-quoted (JSON
// strings are valid YAML), so a name such as 123 or a value such as true stays a string.
const PLAIN_KEY = /^[A-Za-z][A-Za-z0-9_-]*$/;
const YAML11_BOOL = new Set(["y", "n", "yes", "no", "on", "off", "true", "false", "null"]);
function key(k: string): string {
  return PLAIN_KEY.test(k) && !YAML11_BOOL.has(k.toLowerCase()) ? k : JSON.stringify(k);
}
function scalar(v: unknown): string {
  if (typeof v === "string") return JSON.stringify(v);
  if (typeof v === "number" || typeof v === "boolean") return String(v);
  return "null";
}
function isObj(v: unknown): v is Obj {
  return !!v && typeof v === "object" && !Array.isArray(v);
}
function inline(v: unknown): string | null {
  if (Array.isArray(v)) return v.length === 0 ? "[]" : null;
  if (isObj(v)) return Object.keys(v).length === 0 ? "{}" : null;
  return scalar(v);
}
function lines(v: Obj | unknown[], indent: string): string[] {
  const out: string[] = [];
  if (Array.isArray(v)) {
    for (const item of v) {
      const one = inline(item);
      if (one !== null) out.push(`${indent}- ${one}`);
      else {
        const sub = lines(item as Obj | unknown[], indent + "  ");
        out.push(`${indent}- ${sub[0]!.trimStart()}`, ...sub.slice(1));
      }
    }
    return out;
  }
  for (const [k, val] of Object.entries(v)) {
    const one = inline(val);
    if (one !== null) out.push(`${indent}${key(k)}: ${one}`);
    else out.push(`${indent}${key(k)}:`, ...lines(val as Obj | unknown[], indent + "  "));
  }
  return out;
}
export function toYaml(v: Obj): string {
  return lines(v, "").join("\n") + "\n";
}

function doc(apiVersion: string, kind: string, body: Obj, comments: string[] = []): string {
  return [...comments.map((c) => `# ${c}`), `apiVersion: ${apiVersion}`, `kind: ${kind}`, ""].join("\n") + toYaml(body);
}

/** A PodDisruptionBudget over the workload's own selector that lets one pod be down at a time. */
export function pdbYaml(w: { ns: string; name: string; selector: Obj }): string {
  return doc("policy/v1", "PodDisruptionBudget", {
    metadata: { name: `${w.name}-pdb`, namespace: w.ns },
    spec: { maxUnavailable: 1, selector: w.selector },
  });
}

/** Denies all ingress to every pod in the namespace; egress is left alone so DNS keeps working. */
export function defaultDenyYaml(ns: string): string {
  return doc(
    "networking.k8s.io/v1",
    "NetworkPolicy",
    { metadata: { name: "default-deny-ingress", namespace: ns }, spec: { podSelector: {}, policyTypes: ["Ingress"] } },
    [`Blocks all inbound traffic to pods in ${ns} until you add policies that allow it.`],
  );
}

/** Enforces Baseline (refuses privileged and host-access pods) and warns and audits on Restricted. */
export function podSecurityYaml(ns: string): string {
  return doc(
    "v1",
    "Namespace",
    {
      metadata: {
        name: ns,
        labels: {
          "pod-security.kubernetes.io/enforce": "baseline",
          "pod-security.kubernetes.io/warn": "restricted",
          "pod-security.kubernetes.io/audit": "restricted",
        },
      },
    },
    ["Applies only these labels; running pods are not evicted, new ones that break Baseline are refused."],
  );
}

export type AutomountKind = "Deployment" | "StatefulSet" | "DaemonSet" | "CronJob";

/** A partial object (server-side apply) that sets automountServiceAccountToken: false on the pod template. */
export function automountFixYaml(kind: AutomountKind, ns: string, name: string): string {
  const pod = { template: { spec: { automountServiceAccountToken: false } } };
  return doc(
    kind === "CronJob" ? "batch/v1" : "apps/v1",
    kind,
    { metadata: { name, namespace: ns }, spec: kind === "CronJob" ? { jobTemplate: { spec: pod } } : pod },
    [`Only this field changes; the ${kind} rolls its pods. Skip it if the app calls the Kubernetes API.`],
  );
}

const HEADER = [
  "Generated by Kubebay Best practices. Nothing has been applied.",
  "Review it, tick Dry run and press it, then Apply.",
];

function join(docs: string[], extra: string[] = []): string {
  const head = [...HEADER, ...extra].map((c) => `# ${c}`).join("\n") + "\n";
  return head + docs.join("\n---\n");
}

const id = (o: Obj): string => `${str(rec(o.metadata).namespace)}/${str(rec(o.metadata).name)}`;

/** The YAML that would fix a failing check, or undefined when there is no safe, reviewable fix. */
export function fixFor(check: BestPracticeCheck, input: BestPracticesInput): BpFix | undefined {
  if (check.status !== "fail") return undefined;
  const offenders = new Set(check.allOffenders ?? []);
  if (offenders.size === 0) return undefined;

  if (check.id === "pdb") {
    const pdbs = input.pdbs ?? [];
    const docs: string[] = [];
    for (const o of [...(input.deployments ?? []), ...(input.statefulsets ?? [])]) {
      const spec = rec(o.spec);
      const ns = str(rec(o.metadata).namespace);
      const labels = rec(rec(spec.template).metadata).labels as Record<string, string> | undefined;
      const replicas = typeof spec.replicas === "number" ? spec.replicas : 1;
      if (!offenders.has(id(o)) || replicas <= 1) continue;
      if (pdbs.some((p) => str(rec(p.metadata).namespace) === ns && matchesSelector(labels ?? {}, rec(rec(p.spec).selector) as LabelSelector))) continue;
      const selector = Object.keys(rec(spec.selector)).length ? rec(spec.selector) : { matchLabels: labels ?? {} };
      docs.push(pdbYaml({ ns, name: str(rec(o.metadata).name), selector }));
    }
    return docs.length ? { kind: "PodDisruptionBudget", count: docs.length, yaml: join(docs) } : undefined;
  }

  if (check.id === "network-policies" || check.id === "pod-security") {
    const make = check.id === "network-policies" ? defaultDenyYaml : podSecurityYaml;
    const docs = [...offenders].map(make);
    return { kind: check.id === "network-policies" ? "NetworkPolicy" : "Namespace", count: docs.length, yaml: join(docs) };
  }

  if (check.id === "sa-automount") {
    const docs: string[] = [];
    let first: AutomountKind | undefined;
    const kinds: [AutomountKind, Obj[] | undefined][] = [
      ["Deployment", input.deployments],
      ["StatefulSet", input.statefulsets],
      ["DaemonSet", input.daemonsets],
      ["CronJob", input.cronjobs],
    ];
    for (const [kind, items] of kinds) {
      for (const o of items ?? []) {
        if (!offenders.has(id(o))) continue;
        const spec = rec(o.spec);
        const pod = rec(rec(kind === "CronJob" ? rec(rec(spec.jobTemplate).spec).template : spec.template).spec);
        const sa = str(pod.serviceAccountName) || str(pod.serviceAccount);
        if ((sa && sa !== "default") || pod.automountServiceAccountToken === false) continue;
        first ??= kind;
        docs.push(automountFixYaml(kind, str(rec(o.metadata).namespace), str(rec(o.metadata).name)));
      }
    }
    const bare = (input.pods ?? []).filter((p) => offenders.has(id(p))).length;
    const note = bare ? [`${bare} bare pod${bare === 1 ? "" : "s"} left out: a pod can't be changed in place; recreate it with the field set.`] : [];
    return first ? { kind: first, count: docs.length, yaml: join(docs, note) } : undefined;
  }

  return undefined;
}
