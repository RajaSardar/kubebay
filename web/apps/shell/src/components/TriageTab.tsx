import { useState } from "react";
import { Badge, Button, InlineBanner, Row, Spinner, Stack, type BadgeTone } from "@kubebay/ui";
import { triageApi, type TriageEvidenceSection, type TriageFinding, type TriagePreview, type TriageResult } from "../lib/api";

const preStyle = {
  fontSize: "var(--kb-text-xs)",
  whiteSpace: "pre-wrap" as const,
  overflowWrap: "anywhere" as const,
  background: "var(--kb-bg-inset)",
  padding: 8,
  borderRadius: "var(--kb-radius-xs)",
  margin: 0,
  maxHeight: 260,
  overflow: "auto",
};

const likelihoodTone: Record<TriageFinding["likelihood"], BadgeTone | undefined> = { likely: "warn", possible: "info", unlikely: undefined };

function keyFrom(source: string): string {
  return source.startsWith("env:") ? `$${source.slice(4)}` : "your keychain";
}

function Finding({ f, sections }: { f: TriageFinding; sections: Map<string, TriageEvidenceSection> }) {
  return (
    <section aria-label={f.title} style={{ borderTop: "1px solid var(--kb-border-subtle)", paddingTop: 10 }}>
      <Stack gap={2}>
        <Row gap={2} align="center" wrap>
          <span className="strong">{f.title}</span>
          <Badge tone={likelihoodTone[f.likelihood]}>{f.likelihood}</Badge>
        </Row>
        <div className="small">{f.explanation}</div>
        <Stack gap={1}>
          <div className="muted small">Cites</div>
          {f.evidence.map((id) => {
            const s = sections.get(id);
            return (
              <details key={id}>
                <summary className="small" style={{ cursor: "pointer" }}>
                  <span className="mono muted">{id}</span> <span>{s?.title ?? id}</span>
                </summary>
                {s && (
                  <pre className="mono" style={{ ...preStyle, marginTop: 6 }}>
                    {s.text}
                  </pre>
                )}
              </details>
            );
          })}
        </Stack>
        {f.nextSteps.length > 0 && (
          <Stack gap={1}>
            <div className="muted small">Next steps, for you to review</div>
            <ul className="small" style={{ margin: 0, paddingLeft: 18 }}>
              {f.nextSteps.map((step, i) => (
                <li key={i}>{step}</li>
              ))}
            </ul>
          </Stack>
        )}
      </Stack>
    </section>
  );
}

function Answer({ result, sections }: { result: TriageResult; sections: TriageEvidenceSection[] }) {
  const byId = new Map(sections.map((s) => [s.id, s]));
  const usage = (
    <div className="muted small">
      Answered by <span className="mono">{result.model}</span> · {result.inputTokens} tokens in, {result.outputTokens} out
    </div>
  );
  if (result.refusal) {
    return (
      <Stack gap={2}>
        <InlineBanner tone="warn" flush>
          The model declined to answer{result.refusal.category ? ` (${result.refusal.category})` : ""}.
          {result.refusal.explanation ? ` ${result.refusal.explanation}` : ""} Nothing was changed.
        </InlineBanner>
        {usage}
      </Stack>
    );
  }
  const hidden = result.dropped === 1 ? "1 finding" : `${result.dropped} findings`;
  return (
    <Stack gap={3}>
      <Stack gap={1}>
        <div className="strong small">Triage</div>
        <div>{result.summary}</div>
      </Stack>
      {result.findings.length === 0 && <div className="muted small">No cause that the evidence supports.</div>}
      {result.findings.map((f, i) => (
        <Finding key={i} f={f} sections={byId} />
      ))}
      {result.missingEvidence && (
        <div className="small">
          <span className="muted">Evidence that would help: </span>
          {result.missingEvidence}
        </div>
      )}
      {result.dropped > 0 && <div className="muted small">Kubebay hid {hidden} that cited no evidence in this bundle.</div>}
      {usage}
      <div className="muted small">Generated by a model from the evidence below. Check it before you act on it.</div>
    </Stack>
  );
}

/**
 * Backlog #13: gather one pod's evidence on request, show the exact request
 * a Send would make, and, when the user sends it, show the answer with each
 * finding next to the evidence it cites.
 */
export function TriageTab({ cluster, namespace, pod }: { cluster: string; namespace: string; pod: string }) {
  const [preview, setPreview] = useState<TriagePreview | null>(null);
  const [result, setResult] = useState<TriageResult | null>(null);
  const [error, setError] = useState<string | null>(null);
  const [sendError, setSendError] = useState<string | null>(null);
  const [busy, setBusy] = useState(false);
  const [sending, setSending] = useState(false);
  const [copied, setCopied] = useState(false);

  const gather = async () => {
    setBusy(true);
    setError(null);
    setSendError(null);
    try {
      setPreview(await triageApi.preview({ cluster, namespace, pod }));
      setResult(null);
    } catch (e) {
      setError(e instanceof Error ? e.message : String(e));
    } finally {
      setBusy(false);
    }
  };
  const sendIt = async () => {
    if (!preview) return;
    setSending(true);
    setSendError(null);
    try {
      setResult(await triageApi.send(preview.previewId));
    } catch (e) {
      setSendError(e instanceof Error ? e.message : String(e));
    } finally {
      setSending(false);
    }
  };
  const copy = () => {
    const text = preview?.request.messages[0]?.content[0]?.text ?? "";
    void navigator.clipboard
      ?.writeText(text)
      .then(() => {
        setCopied(true);
        setTimeout(() => setCopied(false), 2000);
      })
      .catch(() => {});
  };

  const copyButton = (
    <Button variant="ghost" onClick={copy}>
      {copied ? "Copied" : "Copy evidence"}
    </Button>
  );

  return (
    <div style={{ padding: 14 }}>
      <Stack gap={3}>
        <div className="muted small">
          Gathers this pod&apos;s evidence: the pod and its owners, container states, warnings, recent rollouts and logs,
          with a restarted container&apos;s previous run first and credentials masked. You see all of it before anything
          leaves Kubebay, and nothing leaves until you send it.
        </div>
        <Row gap={2} align="center">
          <Button variant={preview ? "ghost" : undefined} disabled={busy || sending} onClick={() => void gather()}>
            {preview ? "Gather again" : "Gather evidence"}
          </Button>
          {busy && <Spinner label="Gathering evidence…" size={16} />}
        </Row>
        {error && <InlineBanner flush>{error}</InlineBanner>}
        {preview && (
          <Stack gap={3}>
            {result && <Answer result={result} sections={preview.evidence.sections} />}
            <Stack gap={1}>
              <div className="strong small">{result ? "What was sent" : "What would be sent"}</div>
              <Row gap={2} align="center" wrap>
                <span className="muted small">To</span>
                <span className="mono small">{preview.endpoint}</span>
                <span className="muted small">model</span>
                <span className="mono small">{preview.request.model}</span>
              </Row>
              <Row gap={2} align="center" wrap>
                <Badge>about {preview.approxTokens} tokens</Badge>
                <Badge tone={preview.evidence.masked > 0 ? "info" : undefined}>{preview.evidence.masked} values masked</Badge>
                {preview.evidence.truncated && <Badge tone="warn">logs were cut to fit</Badge>}
              </Row>
            </Stack>
            {!result &&
              (preview.keySource ? (
                <Stack gap={2}>
                  <InlineBanner tone="warn" flush>
                    Nothing has been sent. Send makes exactly this request, once, with the API key from{" "}
                    {keyFrom(preview.keySource)}. The model only reads it: nothing in the cluster changes.
                  </InlineBanner>
                  <Row gap={2} align="center" wrap>
                    <Button disabled={sending || busy} onClick={() => void sendIt()}>
                      {`Send to ${preview.request.model}`}
                    </Button>
                    {copyButton}
                    {sending && <Spinner label="Waiting for the answer, which can take a minute or two…" size={16} />}
                  </Row>
                  {sendError && <InlineBanner flush>{sendError}</InlineBanner>}
                </Stack>
              ) : (
                <Stack gap={2}>
                  <InlineBanner tone="warn" flush>
                    Nothing has been sent. To send it from here, add an API key in Settings. Or copy the evidence into the
                    assistant you use.
                  </InlineBanner>
                  <Row gap={2}>{copyButton}</Row>
                </Stack>
              ))}
            {result && <Row gap={2}>{copyButton}</Row>}
            {preview.evidence.sections.map((s) => (
              <Stack key={s.id} gap={1}>
                <Row gap={2} align="center">
                  <span className="mono small muted">{s.id}</span>
                  <span className="strong small">{s.title}</span>
                </Row>
                <pre className="mono" style={preStyle}>
                  {s.text}
                </pre>
              </Stack>
            ))}
            <details>
              <summary className="small strong" style={{ cursor: "pointer" }}>
                Instructions sent with it
              </summary>
              <pre className="mono" style={{ ...preStyle, marginTop: 6 }}>
                {preview.request.system.map((b) => b.text).join("\n\n")}
              </pre>
            </details>
          </Stack>
        )}
      </Stack>
    </div>
  );
}
